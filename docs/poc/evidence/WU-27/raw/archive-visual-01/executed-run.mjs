import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const attempt = process.argv[2];
const command = process.argv.slice(3);
if (!attempt || !command.length) throw Error('Unique attempt and exact command required');
const directory = `docs/poc/evidence/WU-27/raw/${attempt}`;
fs.mkdirSync(directory, { recursive: true });
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const recordFile = (path, bytes) => { fs.writeFileSync(path, bytes, { flag: 'wx' }); return { path, bytes: bytes.length, sha256: hash(bytes) }; };
const commandText = `${command.map(value => `'${value.replaceAll("'", "'\\''")}'`).join(' ')}\n`;
const commandRecord = recordFile(`${directory}/command.txt`, Buffer.from(commandText));
recordFile(`${directory}/executed-run.mjs`, fs.readFileSync(import.meta.filename));
const out = fs.openSync(`${directory}/stdout`, 'wx'), err = fs.openSync(`${directory}/stderr`, 'wx');
const result = spawnSync(command[0], command.slice(1), { stdio: ['ignore', out, err] });
fs.closeSync(out); fs.closeSync(err);
const recorded = path => { const bytes = fs.readFileSync(path); return { path, bytes: bytes.length, sha256: hash(bytes) }; };
const execution = { command: commandRecord, argv: command, node: process.version, exitStatus: result.status, error: result.error?.code ?? null, stdout: recorded(`${directory}/stdout`), stderr: recorded(`${directory}/stderr`) };
recordFile(`${directory}/execution.json`, Buffer.from(JSON.stringify(execution, null, 2) + '\n'));
console.log(JSON.stringify({ attempt, exitStatus: result.status, stdout: execution.stdout.bytes, stderr: execution.stderr.bytes }));
process.exitCode = result.status ?? 1;
